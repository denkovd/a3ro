/* ────────────────────────────────────────────────────────────────
   Bake country borders and coastlines for the globes (roadmap #101).

   Source: Natural Earth admin-0 countries (public domain) via the
   world-atlas TopoJSON. Not a project dependency; run with them
   installed anywhere and point at that folder:

     npm i --prefix /tmp/b world-atlas@2.0.2 topojson-client@3.1.0
     node scripts/bake-borders.mjs /tmp/b/node_modules

   Writes
     lib/globe/borders110.ts       1:110m, embedded (always drawn)
     public/data/borders-50m.bin   1:50m, fetched only when zoomed in

   Format (little-endian Int16): [borderLines, coastLines, then per
   line: nPoints, lon×100, lat×100, …]. Internal borders are the
   TopoJSON mesh between two different countries; coastlines are the
   mesh on one country only. Points closer than `minStep` degrees to
   the previous kept point are dropped (end points always kept).
──────────────────────────────────────────────────────────────── */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";

const modules = process.argv[2];
if (!modules) { console.error("usage: node scripts/bake-borders.mjs <node_modules with world-atlas and topojson-client>"); process.exit(1); }
const require = createRequire(join(modules, "x.js"));
const { mesh } = require("topojson-client");

function lines(topo, filter, minStep) {
  const m = mesh(topo, topo.objects.countries, filter);
  const out = [];
  for (const line of m.coordinates) {
    const kept = [];
    for (let i = 0; i < line.length; i++) {
      const [lon, lat] = line[i];
      const prev = kept[kept.length - 1];
      const last = i === line.length - 1;
      if (prev && !last && Math.hypot(lon - prev[0], lat - prev[1]) < minStep) continue;
      kept.push([lon, lat]);
    }
    if (kept.length >= 2) out.push(kept);
  }
  return out;
}

function encode(borders, coasts) {
  const nums = [borders.length, coasts.length];
  for (const l of [...borders, ...coasts]) {
    if (l.length > 32767) throw new Error("line too long");
    nums.push(l.length);
    for (const [lon, lat] of l) nums.push(Math.round(lon * 100), Math.round(lat * 100));
  }
  const buf = Buffer.alloc(nums.length * 2);
  nums.forEach((v, i) => buf.writeInt16LE(v, i * 2));
  return { buf, points: (nums.length - 2 - borders.length - coasts.length) / 2 };
}

function bake(file, minStep) {
  const topo = JSON.parse(readFileSync(join(modules, "world-atlas", file), "utf8"));
  const borders = lines(topo, (a, b) => a !== b, minStep);
  const coasts = lines(topo, (a, b) => a === b, minStep);
  return encode(borders, coasts);
}

const small = bake("countries-110m.json", 0.4);
mkdirSync("lib/globe", { recursive: true });
writeFileSync("lib/globe/borders110.ts", `/* GENERATED by scripts/bake-borders.mjs: Natural Earth 1:110m (public domain). Do not edit.
   ${small.points} points; format in scripts/bake-borders.mjs. */
export const BORDERS_110_B64 = "${small.buf.toString("base64")}";
`);
const big = bake("countries-50m.json", 0.12);
mkdirSync("public/data", { recursive: true });
writeFileSync("public/data/borders-50m.bin", big.buf);
console.log(`110m: ${small.points} points, ${(small.buf.length / 1024).toFixed(0)} KB (base64 ${(small.buf.length * 4 / 3 / 1024).toFixed(0)} KB)`);
console.log(`50m:  ${big.points} points, ${(big.buf.length / 1024).toFixed(0)} KB`);
